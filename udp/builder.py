"""Generate/check a minimal device definition from the sourced watch profile."""

import argparse
import json
from pathlib import Path

from udp.hardware import BOARD, WATCH, read_json, validate_watch

ROOT = Path(__file__).resolve().parent.parent
GENERATED_HEADER = ROOT / "firmware/watch-v0/main/generated_device_config.h"


def make_manifest(watch, firmware_version="sim-0.1.0"):
    return {
        "type": "manifest",
        "protocol": "udp/1",
        "device_id": watch["id"],
        "firmware_version": firmware_version,
        "capabilities": list(watch["active_capabilities"]),
    }


def generate_header(board, watch):
    errors = validate_watch(board=board, watch=watch)
    if errors:
        raise ValueError("Invalid hardware configuration: " + "; ".join(errors))
    button = next(c for c in watch["components"] if c["role"] == "primary_button")
    gpio = board["pins"][button["wiring"]["signal_pin"]]
    ble = {"v": 1, "id": watch["id"], "caps": watch["active_capabilities"]}
    compact = json.dumps(ble, separators=(",", ":"), ensure_ascii=True)
    return (
        "#pragma once\n"
        "/* GENERATED by python -m udp.builder. DO NOT EDIT. */\n"
        "#define UDP_PROTOCOL_MAJOR 1\n"
        f"#define UDP_BUTTON_GPIO {gpio}\n"
        '#define UDP_BLE_DEVICE_NAME "UDP-W0"\n'
        "#define UDP_DEVICE_ID " + json.dumps(watch["id"]) + "\n"
        "#define UDP_BLE_MANIFEST " + json.dumps(compact) + "\n"
    )


def main():
    parser = argparse.ArgumentParser(description="Generate/check watch firmware configuration")
    parser.add_argument("--check", action="store_true",
                        help="Fail if generated firmware header differs from hardware manifest")
    args = parser.parse_args()
    header = generate_header(read_json(BOARD), read_json(WATCH))
    if args.check:
        if not GENERATED_HEADER.exists() or GENERATED_HEADER.read_text(encoding="utf-8") != header:
            raise SystemExit("Firmware header drift: run python -m udp.builder and commit result")
        print("PASS: firmware header matches watch hardware configuration")
    else:
        GENERATED_HEADER.write_text(header, encoding="utf-8")
        print("Generated " + str(GENERATED_HEADER))


if __name__ == "__main__":
    main()
